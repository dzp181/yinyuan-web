def report(year, status=None, flow_year=2026):
    if not 1900 <= int(year) <= 2100:
        raise ValueError("出生年份需在 1900-2100 之间")
    zi = year_zhi_idx(int(year))
    sx = SHENGXIAO[zi]
    taohua_zhi, fangwei, taohua_sx, meaning = TAOHUA_POS[_GROUP_OF[zi]]

    # 流年信息
    fy_zi = year_zhi_idx(int(flow_year))
    fy_tai_sui = fy_zi == zi
    flags = []
    if fy_tai_sui:
        flags.append("本命年")
    if ZHI_CHONG.get(fy_zi) == zi:
        flags.append("冲太岁")
    if ZHI_HAI.get(fy_zi) == zi:
        flags.append("害太岁")
    if int(flow_year) == 2026 and sx in FLOW_2026:
        stars, brief = FLOW_2026[sx]
    else:
        # 通用流年：流年桃花位 == 本命桃花位 则旺
        fy_tao = TAOHUA_POS[_GROUP_OF[fy_zi]][0]
        stars = 4 if fy_tao == taohua_zhi else 3
        if fy_tai_sui:
            stars = max(2, stars - 1)
        brief = "流年桃花在%s（%s）%s" % (
            fy_tao, TAOHUA_POS[_GROUP_OF[fy_zi]][1],
            "，正应你的本命桃花位——感情机会多" if fy_tao == taohua_zhi else "，感情平稳经营为主")
    if flags:
        brief = "（%s）%s" % ("、".join(flags), brief)

    peaks = PEAK_MONTHS[sx]
    bad = PEAK_MONTHS[sx + "_bad"]
    wu = ZODIAC_WUXING[sx]
    lucky_wx = SHENG[wu]          # 生我者
    lucky_color = COLOR_OF[lucky_wx]

    # 桃花类型提示
